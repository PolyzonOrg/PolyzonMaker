/**
 * That a model was made by an AI, written into the files exported from it, the way the standards that exist
 * ask: IPTC's digital source type «trainedAlgorithmicMedia» and its AI-system fields (Photo Metadata 2025.1),
 * as XMP in a GLB (Khronos KHR_xmp_json_ld), as namespaced metadata in a 3MF, and in words in an STL's
 * header. And an invisible mark in the coordinates themselves: each one's last binary digit set from a hash
 * of the rest, which moves it by a ten-millionth of its size at most, keeps equal points equal, and stays
 * through a copy or a change between STL, 3MF and GLB. A rebuilt or rescaled mesh loses it. The scheme is
 * open, so anyone can check a file with `readMark`: it shows where a model came from, it hides nothing.
 */

export interface Provenance {
	/** The program and its version, e.g. «Polyzon Maker 0.2.1» */
	tool: string;
	/** The AI model that made it, e.g. «TRELLIS.2» */
	system: string;
	/** When, ISO 8601 */
	created: string;
}

/** IPTC NewsCodes: media created by a model trained on sampled content. */
export const AI_SOURCE = 'http://cv.iptc.org/newscodes/digitalsourcetype/trainedAlgorithmicMedia';
export const IPTC_EXT = 'http://iptc.org/std/Iptc4xmpExt/2008-02-29/';
const XMP = 'http://ns.adobe.com/xap/1.0/';

/** The STL header: 80 bytes of plain ASCII, the only place an STL has for words. */
export function stlHeader(p: Provenance): string {
	const ascii = (s: string) => s.replace(/[^\x20-\x7e]/g, '?');
	return ascii(`AI-generated by ${p.system} in ${p.tool}; IPTC trainedAlgorithmicMedia`).slice(0, 79);
}

/** Metadata for a 3MF model: the core names first, then IPTC's under its own namespace. */
export function threeMfMetadata(p: Provenance): { namespaces: Record<string, string>; entries: [string, string][] } {
	return {
		namespaces: { Iptc4xmpExt: IPTC_EXT },
		entries: [
			['Description', `AI-generated by ${p.system} in ${p.tool}`],
			['CreationDate', p.created.slice(0, 10)],
			['Iptc4xmpExt:DigitalSourceType', AI_SOURCE],
			['Iptc4xmpExt:AISystemUsed', p.system]
		]
	};
}

/** One KHR_xmp_json_ld packet for a glTF asset. */
export function xmpPacket(p: Provenance): Record<string, unknown> {
	return {
		'@context': { Iptc4xmpExt: IPTC_EXT, xmp: XMP },
		'@id': '',
		'Iptc4xmpExt:DigitalSourceType': AI_SOURCE,
		'Iptc4xmpExt:AISystemUsed': p.system,
		'xmp:CreatorTool': p.tool,
		'xmp:CreateDate': p.created
	};
}

const SALT = 0x504d4b31; // «PMK1»

/** The bit a coordinate's last binary digit should hold, from the rest of its bits. */
function bitFor(rest: number): number {
	let h = (rest ^ SALT) >>> 0;
	h = Math.imul(h ^ (h >>> 16), 0x85ebca6b);
	h = Math.imul(h ^ (h >>> 13), 0xc2b2ae35);
	return (h ^ (h >>> 16)) & 1;
}

/** Zeros, infinities and NaN carry no mark: a zero stays exactly zero. */
const markable = (bits: number) => (bits & 0x7fffffff) !== 0 && (bits & 0x7f800000) !== 0x7f800000;

/** A copy of float32 coordinates with the invisible mark in them. */
export function markCoordinates(values: Float32Array): Float32Array {
	const out = values.slice();
	const bits = new Uint32Array(out.buffer, out.byteOffset, out.length);
	for (let i = 0; i < bits.length; i++) {
		const b = bits[i];
		if (!markable(b)) continue;
		const rest = (b & 0xfffffffe) >>> 0;
		bits[i] = (rest | bitFor(rest)) >>> 0;
	}
	return out;
}

/**
 * Whether float32 coordinates carry the mark: the share of them whose last digit agrees. A model as it came
 * from anywhere else agrees by chance, about half the time; a marked one, every time.
 */
export function readMark(values: Float32Array): { checked: number; share: number; marked: boolean } {
	const bits = new Uint32Array(values.buffer, values.byteOffset, values.length);
	let checked = 0;
	let agree = 0;
	for (let i = 0; i < bits.length; i++) {
		const b = bits[i];
		if (!markable(b)) continue;
		checked++;
		if ((b & 1) === bitFor((b & 0xfffffffe) >>> 0)) agree++;
	}
	const share = checked ? agree / checked : 0;
	// 64 coordinates agreeing by chance: one in 10^19
	return { checked, share, marked: checked >= 64 && share >= 0.98 };
}
