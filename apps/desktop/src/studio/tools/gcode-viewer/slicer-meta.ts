/**
 * What a slicer wrote about its own result: print time, filament per
 * extruder, the slicer's name. Read from G-code comments (PrusaSlicer,
 * SuperSlicer, OrcaSlicer, Bambu Studio, Cura, Creality Print, Simplify3D)
 * and from the same «key = value» lines in .bgcode metadata blocks.
 *
 * Feed comment lines (without the leading «;») into a MetaReader, then call
 * result(). Values are assigned, not summed, so reading the same line twice
 * (head and tail of a small file overlap) does not double anything.
 */

export interface FilamentUse {
	/** Grams of this filament, when the slicer wrote them. */
	grams: number | null;
	/** Length in millimetres, when the slicer wrote it. */
	mm: number | null;
	type: string | null;
	/** #rrggbb */
	color: string | null;
}

export interface SlicerMeta {
	slicer: string | null;
	/** Whole print, seconds. */
	timeSec: number | null;
	/** Total filament, grams (all extruders, purge and tower included). */
	grams: number | null;
	/** Total filament length, millimetres. */
	mm: number | null;
	filaments: FilamentUse[];
	/** Material of the prime/wipe tower, grams (part of `grams`). */
	towerGrams: number | null;
	layerCount: number | null;
	diameter: number | null;
	density: number | null;
}

/**
 * «1d 2h 3m 4s», «2h 35m», «45m 10s», «1 hours 2 minutes», «01:02:03» or a
 * bare number of seconds → seconds. null when nothing readable.
 */
export function parseDuration(raw: string): number | null {
	const s = raw.trim().toLowerCase();
	if (!s) return null;
	if (/^\d+(?:\.\d+)?$/.test(s)) return Math.round(Number(s));
	const clock = /^(\d+):(\d{1,2})(?::(\d{1,2}))?$/.exec(s);
	if (clock) {
		// «h:mm» or «h:mm:ss».
		return Number(clock[1]) * 3600 + Number(clock[2]) * 60 + Number(clock[3] ?? 0);
	}
	const units: Record<string, number> = { d: 86400, h: 3600, m: 60, s: 1 };
	let total = 0;
	let found = false;
	const re =
		/(\d+(?:\.\d+)?)\s*(d(?:ays?)?|h(?:ours?|rs?)?|m(?:in(?:ute)?s?)?|s(?:ec(?:ond)?s?)?)(?![a-z])/g;
	for (const m of s.matchAll(re)) {
		total += Number(m[1]) * units[m[2][0]];
		found = true;
	}
	return found ? Math.round(total) : null;
}

/** «12.3, 0.5» / «12.3;0.5» / «1.2m, 0.3m» → numbers (units stripped). */
function numberList(raw: string): number[] {
	return raw
		.split(/[,;]/)
		.map((part) => Number.parseFloat(part.trim()))
		.filter((n) => Number.isFinite(n));
}

function stringList(raw: string): string[] {
	return raw
		.split(/[;,]/)
		.map((part) => part.trim().replace(/^"|"$/g, ''))
		.filter(Boolean);
}

const COLOR = /^#[0-9a-f]{6}$/i;

/** Slicer name from a «generated by …» line, in the words users know. */
function slicerName(raw: string): string {
	const name = raw.trim();
	const known: [RegExp, string][] = [
		[/bambu\s*studio/i, 'Bambu Studio'],
		[/orca\s*slicer/i, 'OrcaSlicer'],
		[/super\s*slicer/i, 'SuperSlicer'],
		[/prusa\s*slicer/i, 'PrusaSlicer'],
		[/creality[_\s]*print/i, 'Creality Print'],
		[/anycubic/i, 'Anycubic Slicer'],
		[/elegoo/i, 'ElegooSlicer'],
		[/cura/i, 'Cura'],
		[/simplify3d/i, 'Simplify3D'],
		[/ideamaker/i, 'ideaMaker'],
		[/slic3r/i, 'Slic3r']
	];
	for (const [re, label] of known) if (re.test(name)) return label;
	return name.slice(0, 40);
}

export class MetaReader {
	private slicer: string | null = null;
	private time: number | null = null;
	private gramsTotal: number | null = null;
	private gramsList: number[] = [];
	private mmTotal: number | null = null;
	private mmList: number[] = [];
	private types: string[] = [];
	private colors: string[] = [];
	private tower: number | null = null;
	private layers: number | null = null;
	private diameters: number[] = [];
	private densities: number[] = [];
	private s3dWeight: number | null = null;

	/** One comment line, without the leading «;». Cheap for lines it does not know. */
	line(raw: string): void {
		const t = raw.trim();
		if (t.length < 4) return;
		const c = t.charCodeAt(0) | 32; // lower-case first letter
		// Most comments in a big file are ;TYPE:, ;WIDTH:, ;HEIGHT:, ;Z: — skip fast.
		if (t.length < 12 && !/^time:|^layer_count:/i.test(t)) return;

		let m: RegExpExecArray | null;
		if (c === 103 && (m = /^generated (?:by|with)\s+(.+?)(?:\s+on\s+\d.*)?$/i.exec(t))) {
			this.slicer ??= slicerName(m[1]);
			return;
		}
		if ((m = /^g-code generated by\s+(.+)$/i.exec(t)) || (m = /^sliced by\s+(.+)$/i.exec(t))) {
			this.slicer ??= slicerName(m[1]);
			return;
		}
		// Time. Bambu writes both on one line: «model printing time: …; total estimated time: …».
		if ((m = /total estimated time\s*[:=]\s*([^;]+)/i.exec(t))) {
			this.time = parseDuration(m[1]) ?? this.time;
			return;
		}
		if ((m = /^estimated printing time(?:\s*\(normal mode\))?\s*[:=]\s*(.+)$/i.exec(t))) {
			this.time = parseDuration(m[1]) ?? this.time;
			return;
		}
		if ((m = /^(?:print\.)?time:\s*(\d+(?:\.\d+)?)\s*$/i.exec(t))) {
			this.time = Math.round(Number(m[1]));
			return;
		}
		if ((m = /^(?:build|print) time:\s*(.+)$/i.exec(t))) {
			this.time = parseDuration(m[1]) ?? this.time;
			return;
		}
		// Filament weight.
		if ((m = /^total filament used for wipe tower \[g\]\s*[:=]\s*(.+)$/i.exec(t))) {
			this.tower = numberList(m[1])[0] ?? null;
			return;
		}
		if ((m = /^total filament (?:used|weight) \[g\]\s*[:=]\s*(.+)$/i.exec(t))) {
			const list = numberList(m[1]);
			if (list.length > 1) this.gramsList = list;
			this.gramsTotal = list.reduce((a, b) => a + b, 0);
			return;
		}
		if ((m = /^filament used \[g\]\s*[:=]\s*(.+)$/i.exec(t))) {
			this.gramsList = numberList(m[1]);
			return;
		}
		if ((m = /^total filament length \[mm\]\s*[:=]\s*(.+)$/i.exec(t))) {
			const list = numberList(m[1]);
			if (list.length > 1) this.mmList = list;
			this.mmTotal = list.reduce((a, b) => a + b, 0);
			return;
		}
		if ((m = /^filament used \[mm\]\s*[:=]\s*(.+)$/i.exec(t))) {
			this.mmList = numberList(m[1]);
			return;
		}
		// Cura: «Filament used: 1.23456m, 0.2m» (metres).
		if ((m = /^filament used:\s*(.+)$/i.exec(t))) {
			const raw = m[1];
			const list = numberList(raw);
			if (/\d\s*g\b/i.test(raw) && !/m\b/i.test(raw)) this.gramsList = list;
			else this.mmList = list.map((v) => (/mm\b/i.test(raw) ? v : v * 1000));
			return;
		}
		// Simplify3D build summary.
		if ((m = /^filament length:\s*([\d.]+)\s*mm/i.exec(t))) {
			this.mmTotal = Number(m[1]);
			return;
		}
		if ((m = /^plastic weight:\s*([\d.]+)\s*g/i.exec(t))) {
			this.s3dWeight = Number(m[1]);
			return;
		}
		// Layers.
		if (
			(m = /^total layers? (?:count|number)\s*[:=]\s*(\d+)/i.exec(t)) ||
			(m = /^layer_count:\s*(\d+)/i.exec(t))
		) {
			this.layers = Number(m[1]);
			return;
		}
		// Filament description (config blocks).
		if ((m = /^filament_type\s*=\s*(.+)$/i.exec(t))) {
			this.types = stringList(m[1]);
			return;
		}
		if ((m = /^(?:filament_colou?r|extruder_colou?r)\s*=\s*(.+)$/i.exec(t))) {
			const list = stringList(m[1]).filter((v) => COLOR.test(v));
			// extruder_colour is often empty («""»); filament_colour wins when both exist.
			if (list.length && (/^filament/i.test(t) || !this.colors.length)) this.colors = list;
			return;
		}
		if ((m = /^filament_diameter\s*=\s*(.+)$/i.exec(t))) {
			this.diameters = numberList(m[1]);
			return;
		}
		if ((m = /^filament_density\s*=\s*(.+)$/i.exec(t))) {
			this.densities = numberList(m[1]);
		}
	}

	/** Set the slicer name when it is known from elsewhere (e.g. a 3MF header). */
	setSlicer(name: string): void {
		this.slicer ??= slicerName(name);
	}

	result(): SlicerMeta {
		const count = Math.max(this.gramsList.length, this.mmList.length);
		const filaments: FilamentUse[] = [];
		for (let i = 0; i < count; i++) {
			const grams = this.gramsList[i] ?? null;
			const mm = this.mmList[i] ?? null;
			// Unused extruders of a multi-tool profile are listed with zeros.
			if (!grams && !mm) continue;
			filaments.push({
				grams,
				mm,
				type: this.types[i] ?? null,
				color: this.colors[i] ?? null
			});
		}
		const listGrams = this.gramsList.length ? this.gramsList.reduce((a, b) => a + b, 0) : null;
		const listMm = this.mmList.length ? this.mmList.reduce((a, b) => a + b, 0) : null;
		return {
			slicer: this.slicer,
			timeSec: this.time,
			grams: this.gramsTotal ?? listGrams ?? this.s3dWeight,
			mm: this.mmTotal ?? listMm,
			filaments,
			towerGrams: this.tower && this.tower > 0 ? this.tower : null,
			layerCount: this.layers,
			diameter: this.diameters[0] ?? null,
			density: this.densities[0] ?? null
		};
	}
}

/** Every comment line of a G-code text (or a «key = value» block). */
export function readSlicerMeta(text: string, reader = new MetaReader()): SlicerMeta {
	let start = 0;
	// The next «;» is searched again only once passed: linear on long comment-free stretches.
	let semi = text.indexOf(';');
	while (start < text.length && semi >= 0) {
		let end = text.indexOf('\n', start);
		if (end < 0) end = text.length;
		if (semi < start) semi = text.indexOf(';', start);
		if (semi < 0) break;
		if (semi < end) reader.line(text.slice(semi + 1, end));
		start = end + 1;
	}
	return reader.result();
}
